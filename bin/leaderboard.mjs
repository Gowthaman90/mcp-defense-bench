#!/usr/bin/env node
/**
 * Comparative leaderboard: reads every measured adapter coverage.json + the rubric, and renders a
 * per-vector × per-tool matrix, per-tool totals, the defense-in-depth (complementarity) view, and —
 * since v0.7.0 — three more things a reviewer asked for:
 *   - coverage PER PROTOCOL REVISION (rubric `appliesTo`), so numbers are never quoted revision-free;
 *   - HELD-OUT coverage beside development coverage (results/heldout/, docs/HELD-OUT-PROTOCOL.md);
 *   - the FALSE-POSITIVE RATE on the benign-only corpus with a 95% interval (results/benign/).
 *
 * Only adapters with measuredBy (i.e. produced by bin/run.mjs) are included — self-reported claims
 * are excluded so the board reflects verified results.  Usage: node bin/leaderboard.mjs
 */
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const rubric = JSON.parse(readFileSync(join(root, "rubric", "crosswalk.json"), "utf8"));
const ids = rubric.vectors.map((v) => v.id);
const WEIGHT = { enforce: 1, detect: 0.5, none: 0, unknown: 0 };
const glyph = { enforce: "🟢", detect: "🟡", none: "·", unknown: "?" };
const pct = (x, n) => `${((x / n) * 100).toFixed(0)}%`;

const tools = [];
for (const d of readdirSync(join(root, "adapters"))) {
  const p = join(root, "adapters", d, "coverage.json");
  if (!existsSync(p)) continue;
  const c = JSON.parse(readFileSync(p, "utf8"));
  if (!c.measuredBy) continue; // verified results only
  c._dir = d;
  const ho = join(root, "results", "heldout", `${d}.json`);
  c._heldout = existsSync(ho) ? JSON.parse(readFileSync(ho, "utf8")) : null;
  const be = join(root, "results", "benign", `${d}.json`);
  c._benign = existsSync(be) ? JSON.parse(readFileSync(be, "utf8")).summary : null;
  const dev = join(root, "results", `${d}.json`);
  c._dev = existsSync(dev) ? JSON.parse(readFileSync(dev, "utf8")).summary : null;
  tools.push(c);
}
tools.sort((a, b) => a.tool.localeCompare(b.tool));

const lvl = (c, id) => c.coverage?.[id]?.level ?? "unknown";
const cell = (c, id) => c.coverage?.[id];
const robustOf = (cov, id) => (typeof cov?.[id]?.robustCoverage === "number" ? cov[id].robustCoverage : (WEIGHT[cov?.[id]?.level ?? "unknown"] ?? 0));
const robustW = (c, subset = ids) => subset.reduce((a, id) => a + robustOf(c.coverage, id), 0);
const capabilityW = (c, subset = ids) => subset.reduce((a, id) => a + (typeof cell(c, id)?.capability === "number" ? cell(c, id).capability : (WEIGHT[lvl(c, id)] ?? 0)), 0);

// Protocol-revision subsets.
const revisions = rubric._specRevisions?.known ?? [];
const latest = rubric._specRevisions?.latest ?? revisions.at(-1);
const appliesTo = (v, rev) => !Array.isArray(v.appliesTo) || v.appliesTo.includes(rev);
const idsFor = (rev) => rubric.vectors.filter((v) => appliesTo(v, rev)).map((v) => v.id);
const newInLatest = rubric.vectors.filter((v) => Array.isArray(v.appliesTo) && v.appliesTo.length === 1 && v.appliesTo[0] === latest).map((v) => v.id);
const original = ids.filter((id) => !newInLatest.includes(id));

const L = [];
L.push("# Leaderboard (verified)", "");
L.push(`_Generated by \`bin/leaderboard.mjs\` from measured runs. Rubric v${rubric.version}, ${ids.length} vectors (${original.length} pre-existing + ${newInLatest.length} introduced by the ${latest} protocol revision)._`, "");

// Totals
L.push("## Coverage of the full attack surface", "");
L.push(
  "**CorpusRobustCoverage** (headline) = mean detection across *all* fixtures of a vector, including evasion variants; a false positive on any benign variant scores that vector 0. **Capability** = best-case (detects ≥1 fixture). Where the two diverge, the tool is brittle to evasion. **This is a descriptive coverage measure over a fixed, non-exhaustive corpus — NOT a procurement or substitutability ranking:** a higher score does not mean a tool better closes *your* gap, and tools at different architectural layers are not substitutable. _Metric fix + scoping credited to M. Brighindi; a decision-indexed RequiredGapClosure metric is planned (see `docs/CHANGELOG-scoring.md`)._",
  "",
);
L.push("| Tool | Class | CorpusRobustCoverage | Capability | 🟢 enforce | 🟡 detect | · none | FP (matched controls) |");
L.push("|---|---|--:|--:|--:|--:|--:|--:|");
for (const c of tools) {
  const r = robustW(c);
  const cap = capabilityW(c);
  const n = { enforce: 0, detect: 0, none: 0, unknown: 0 };
  for (const id of ids) n[lvl(c, id)] = (n[lvl(c, id)] ?? 0) + 1;
  const fp = c._dev ? `${c._dev.falsePositives}/${c._dev.casesRun}` : "—";
  L.push(`| **${c.tool}** | ${c.class ?? "?"} | ${pct(r, ids.length)} (${r.toFixed(1)}/${ids.length}) | ${pct(cap, ids.length)} (${cap.toFixed(1)}/${ids.length}) | ${n.enforce} | ${n.detect} | ${n.none} | ${fp} |`);
}
L.push("");

// Per-revision view
L.push("## Coverage per protocol revision", "");
L.push(`A coverage number is only meaningful relative to a protocol revision (rubric \`appliesTo\`). The ${newInLatest.length} vectors introduced by **${latest}** did not exist before it; a tool built for the earlier shape is not "missing" them so much as not yet speaking the revision. Both views are reported.`, "");
const revCols = revisions.map((rev) => `${rev} (${idsFor(rev).length} vectors)`);
L.push(`| Tool | ${revCols.join(" | ")} | ${latest}-only vectors (${newInLatest.length}) |`);
L.push(`|---|${revisions.map(() => "--:").join("|")}|--:|`);
for (const c of tools) {
  const cols = revisions.map((rev) => { const sub = idsFor(rev); const r = robustW(c, sub); return `${pct(r, sub.length)} (${r.toFixed(1)}/${sub.length})`; });
  const rn = robustW(c, newInLatest);
  L.push(`| **${c.tool}** | ${cols.join(" | ")} | ${newInLatest.length ? `${pct(rn, newInLatest.length)} (${rn.toFixed(1)}/${newInLatest.length})` : "—"} |`);
}
L.push("");

// Held-out view
const anyHeldout = tools.some((t) => t._heldout);
if (anyHeldout) {
  L.push("## Development vs held-out coverage", "");
  L.push("Held-out fixtures were authored **after** every defender's detection code was frozen, from vector descriptions and the attack literature only, under the pre-registered rules in `docs/HELD-OUT-PROTOCOL.md` (domain / lexical / surface / encoding shifts, no reuse of development phrasing or hosts). The **generalisation gap** is development minus held-out RobustCoverage over the vectors the held-out set covers. A large gap is a finding about the tool.", "");
  L.push("| Tool | Dev RobustCoverage (same vectors) | Held-out RobustCoverage | Gap | Held-out fixtures | Held-out FP |");
  L.push("|---|--:|--:|--:|--:|--:|");
  for (const c of tools) {
    if (!c._heldout) { L.push(`| **${c.tool}** | — | not yet measured | — | — | — |`); continue; }
    const hcov = c._heldout.coverage ?? {};
    const hIds = ids.filter((id) => hcov[id]?.verified);
    const dev = robustW(c, hIds), ho = hIds.reduce((a, id) => a + robustOf(hcov, id), 0);
    L.push(`| **${c.tool}** | ${pct(dev, hIds.length)} (${dev.toFixed(1)}/${hIds.length}) | ${pct(ho, hIds.length)} (${ho.toFixed(1)}/${hIds.length}) | ${(((dev - ho) / hIds.length) * 100).toFixed(0)} pts | ${c._heldout.summary.casesRun} | ${c._heldout.summary.falsePositives}/${c._heldout.summary.casesRun} |`);
  }
  L.push("");
  L.push("### Per-vector: development → held-out", "");
  L.push(`| Vector | ${tools.filter((t) => t._heldout).map((t) => t.tool).join(" | ")} |`);
  L.push(`|---|${tools.filter((t) => t._heldout).map(() => "--").join("|")}|`);
  for (const v of rubric.vectors) {
    const cells = tools.filter((t) => t._heldout).map((t) => { const h = t._heldout.coverage?.[v.id]; if (!h?.verified) return "n/a"; const d = t.coverage?.[v.id]; return `${glyph[d?.level ?? "unknown"]} ${((d?.robustCoverage ?? 0) * 100).toFixed(0)}% → ${glyph[h.level]} ${((h.robustCoverage ?? 0) * 100).toFixed(0)}%`; });
    if (cells.every((x) => x === "n/a")) continue;
    L.push(`| ${v.name} | ${cells.join(" | ")} |`);
  }
  L.push("");
}

// Benign corpus / FP view
const anyBenign = tools.some((t) => t._benign);
if (anyBenign) {
  L.push("## False-positive rate on the benign-only corpus", "");
  L.push("Matched controls (above) test *discrimination* on near-identical pairs; this corpus tests *specificity at scale* on realistic non-attack inputs — verbatim tool definitions harvested from public MCP servers, plus authored hard negatives (benign text that mentions passwords, deletion, shells, URLs). Every flag here is a false positive. Interval: Wilson 95%.", "");
  L.push("| Tool | Items | False positives | FP rate | 95% CI | by kind |");
  L.push("|---|--:|--:|--:|--:|---|");
  for (const c of tools) {
    if (!c._benign) { L.push(`| **${c.tool}** | — | not yet measured | — | — | — |`); continue; }
    const b = c._benign;
    const kinds = Object.entries(b.byKind ?? {}).map(([k, v]) => `${k} ${v.fp}/${v.n}`).join(", ");
    L.push(`| **${c.tool}** | ${b.items} | ${b.falsePositives} | ${(b.fpRate * 100).toFixed(1)}% | ${(b.fpRate95ci.lo * 100).toFixed(1)}–${(b.fpRate95ci.hi * 100).toFixed(1)}% | ${kinds} |`);
  }
  L.push("");
}

// Matrix
L.push("## Per-vector matrix", "");
L.push(`| Vector | Layer | Applies to | ${tools.map((t) => t.tool).join(" | ")} |`);
L.push(`|---|---|---|${tools.map(() => "--").join("|")}|`);
for (const v of rubric.vectors) {
  const rev = Array.isArray(v.appliesTo) && v.appliesTo.length === 1 ? v.appliesTo[0] : "all";
  L.push(`| ${v.name} | ${v.mcpLayer[0]} | ${rev} | ${tools.map((t) => glyph[lvl(t, v.id)]).join(" | ")} |`);
}
L.push("");

// Defense-in-depth
const anyCovers = (id) => tools.some((t) => ["detect", "enforce"].includes(lvl(t, id)));
const covered = ids.filter(anyCovers);
const uncovered = ids.filter((id) => !anyCovers(id));
L.push("## Defense-in-depth view", "");
L.push(`- **Covered by at least one tool:** ${covered.length}/${ids.length}`);
L.push(`- **Covered by NO measured tool:** ${uncovered.length}/${ids.length} — ${uncovered.join(", ") || "none"}`);
const complementary = covered.filter((id) => {
  const levels = tools.map((t) => lvl(t, id));
  return new Set(levels.filter((x) => x !== "none" && x !== "unknown")).size >= 1 && levels.includes("none");
});
L.push(`- **Complementarity:** ${complementary.length} vectors are caught by some tools but missed by others — evidence that no single proxy suffices.`);
L.push("");
L.push("> **Caveat:** absolute scores are corpus-dependent. Read the matrix for *which* vectors each tool covers, not just the totals, and read the per-revision table before quoting any single number. See `docs/ADAPTERS.md`.");

process.stdout.write(L.join("\n") + "\n");
