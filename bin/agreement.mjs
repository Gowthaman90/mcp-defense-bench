#!/usr/bin/env node
/**
 * Inter-rater agreement for the crosswalk (see rubric/RATING-CODEBOOK.md).
 *
 * Compares the primary crosswalk (Rater A = rubric/crosswalk.json) with one or more independent
 * rating sheets (rubric/ratings/rater-*.json). Reports, per framework dimension:
 *   - primary-label Cohen's κ (first element of mcpLayer / stride),
 *   - mean per-vector Jaccard over the full label sets,
 *   - pooled per-label Cohen's κ (presence/absence of each label across vectors),
 * plus a vector-by-vector disagreement list for adjudication.
 *
 * Usage: node bin/agreement.mjs [rater-B.json ...]   (default: every rubric/ratings/rater-*.json
 *        except the template). Add --md to emit Markdown for docs/AGREEMENT.md.
 */
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const rubric = JSON.parse(readFileSync(join(root, "rubric", "crosswalk.json"), "utf8"));
const DIMS = ["mcpLayer", "stride", "nistAiRmf", "owaspLlm2025", "owaspAgentic2026", "nsaGuidance"];
const PRIMARY_DIMS = ["mcpLayer", "stride"];

const args = process.argv.slice(2);
const md = args.includes("--md");
let files = args.filter((a) => !a.startsWith("--"));
if (!files.length) {
  files = readdirSync(join(root, "rubric", "ratings"))
    .filter((f) => /^rater-[^T].*\.json$/.test(f) && f !== "rater-TEMPLATE.json")
    .map((f) => join(root, "rubric", "ratings", f));
}
if (!files.length) {
  console.error("no rating sheets found in rubric/ratings/");
  process.exit(1);
}

/** Cohen's κ for two label vectors over the same items. */
function kappa(a, b) {
  const n = a.length;
  if (!n) return NaN;
  const labels = [...new Set([...a, ...b])];
  let po = 0;
  for (let i = 0; i < n; i++) if (a[i] === b[i]) po++;
  po /= n;
  let pe = 0;
  for (const l of labels) {
    const pa = a.filter((x) => x === l).length / n;
    const pb = b.filter((x) => x === l).length / n;
    pe += pa * pb;
  }
  return pe === 1 ? 1 : (po - pe) / (1 - pe);
}
const jaccard = (A, B) => {
  const a = new Set(A), b = new Set(B);
  if (!a.size && !b.size) return 1;
  let inter = 0;
  for (const x of a) if (b.has(x)) inter++;
  return inter / (a.size + b.size - inter);
};
const f2 = (x) => (Number.isNaN(x) ? "n/a" : x.toFixed(2));

const out = [];
const say = (s = "") => out.push(s);

for (const file of files) {
  const sheet = JSON.parse(readFileSync(file, "utf8"));
  const ratings = sheet.ratings ?? {};
  const ids = rubric.vectors.map((v) => v.id).filter((id) => ratings[id]);
  const skipped = rubric.vectors.length - ids.length;
  const A = Object.fromEntries(rubric.vectors.map((v) => [v.id, v]));

  say(`## Rater A (crosswalk v${rubric.version}) vs Rater ${sheet._rater?.id ?? "?"} — ${sheet._rater?.who ?? file}`);
  say();
  say(`Vectors compared: **${ids.length}** (${skipped} not rated by this rater). Blind: ${sheet._rater?.blind ? "yes" : "no"}.${sheet._disclosure ? " Disclosure: " + sheet._disclosure : ""}`);
  say();
  say("| Dimension | Primary-label κ | Mean Jaccard (sets) | Pooled per-label κ | Exact-set match |");
  say("|---|--:|--:|--:|--:|");
  const disagreements = [];
  for (const dim of DIMS) {
    const a = ids.map((id) => A[id][dim] ?? []);
    const b = ids.map((id) => ratings[id][dim] ?? []);
    const primK = PRIMARY_DIMS.includes(dim) ? kappa(a.map((x) => x[0] ?? "∅"), b.map((x) => x[0] ?? "∅")) : NaN;
    const jac = a.map((x, i) => jaccard(x, b[i]));
    const meanJ = jac.reduce((s, x) => s + x, 0) / (jac.length || 1);
    const labels = [...new Set([...a.flat(), ...b.flat()])];
    const pa = [], pb = [];
    for (const l of labels) for (let i = 0; i < ids.length; i++) { pa.push(a[i].includes(l) ? 1 : 0); pb.push(b[i].includes(l) ? 1 : 0); }
    const pooledK = kappa(pa, pb);
    const exact = jac.filter((x) => x === 1).length;
    say(`| ${dim} | ${f2(primK)} | ${f2(meanJ)} | ${f2(pooledK)} | ${exact}/${ids.length} |`);
    ids.forEach((id, i) => { if (jac[i] < 1) disagreements.push({ id, dim, A: a[i], B: b[i] }); });
  }
  say();
  say(`### Disagreements for adjudication (${disagreements.length})`);
  say();
  say("| Vector | Dimension | Rater A | Rater B |");
  say("|---|---|---|---|");
  for (const d of disagreements) say(`| ${d.id} | ${d.dim} | ${d.A.join(", ") || "∅"} | ${d.B.join(", ") || "∅"} |`);
  say();
}
say("_κ interpretation (Landis & Koch): <0 poor · 0.00–0.20 slight · 0.21–0.40 fair · 0.41–0.60 moderate · 0.61–0.80 substantial · 0.81–1.00 almost perfect. Jaccard = |A∩B| / |A∪B| per vector, averaged._");
process.stdout.write((md ? "# Crosswalk inter-rater agreement\n\n_Generated by `bin/agreement.mjs`._\n\n" : "") + out.join("\n") + "\n");
